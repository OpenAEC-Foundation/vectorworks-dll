    fn document_palette_from_cmyk() {
        // sample 100: the added colour is RGB 12345, 23456, 34567 of 65535, stored as C M Y K
        let f = |v: f32| v.to_le_bytes().to_vec();
        let bytes = crate::dmdt::tests::record(b"DCDN", &[(2, 8, 1, f(0.642_867_5)), (3, 8, 1, f(0.321_433_7)), (4, 8, 1, f(0.0)), (5, 8, 1, f(0.472_541_4))]);
        let record = vwx_core::container::Record { offset: 0, bytes: &bytes };
        let palette = super::Palette::from_data(&crate::dmdt::Data::parse(&record).unwrap()).unwrap();
        assert_eq!(palette.color(0), Some([48, 91, 135]));
        assert_eq!(palette.color(257), Some([0, 0, 0]));
    }
