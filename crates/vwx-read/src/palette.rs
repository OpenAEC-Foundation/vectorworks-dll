//! Colours: a drawn object names its colours by index into the palette of the document.
//!
//! The palette is the `TDMD` record with key `DCDN` at document level: fields 2 to 5 are the
//! cyan, magenta, yellow and black of every colour as `f32` (0..1), field 1 the number of colours
//! in use. Indexes 0..=1238 are the same in every document; colours a document adds follow.
//! Checked against the scripting API for all 1239 fixed colours and for added ones
//! (`tools/oracle/jobs/002_palette.py`, sample 100).

use crate::dmdt::Data;

/// The colours of a document, by index.
#[derive(Debug, Clone, Default)]
pub struct Palette {
    colors: Vec<[u8; 3]>,
}

impl Palette {
    /// The palette stored in a `DCDN` record.
    pub fn from_data(data: &Data) -> Option<Palette> {
        let [c, m, y, k] = [2, 3, 4, 5].map(|n| data.field(n).map(|f| f.f32s()));
        let (c, m, y, k) = (c?, m?, y?, k?);
        let colors = (0..c.len().min(m.len()).min(y.len()).min(k.len()))
            .map(|i| [c[i], m[i], y[i]].map(|ink| ((1.0 - ink) * (1.0 - k[i]) * 255.0).round().clamp(0.0, 255.0) as u8))
            .collect();
        Some(Palette { colors })
    }

    /// sRGB of palette index `index`: from the document, else from the fixed colours.
    pub fn color(&self, index: u16) -> Option<[u8; 3]> {
        self.colors.get(index as usize).copied().or_else(|| color(index))
    }
}

/// sRGB of palette index `index`, when it is one of the fixed colours (for a file without a
/// palette record).
pub fn color(index: u16) -> Option<[u8; 3]> {
    PALETTE.get(index as usize).copied()
}

