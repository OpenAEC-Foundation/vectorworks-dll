# Generates crates/vwx-xt/src/schema.rs: the node types of Parasolid XT base schema 13006 with
# the fields that are transmitted, in order.
#
# Source: Annex E ("XT B-Rep data segment") of Siemens' public "JT File Format Reference Version
# 10.0" (2014), struct definitions and the node type table. Make the input with
#
#     pdftotext -raw -f 430 -l 530 JT-v10-file-format-reference-rev-B.pdf xt_raw.txt
#     python gen_xt_schema.py xt_raw.txt ../crates/vwx-xt/src/schema.rs
#
# The reference prints the structs of a schema later than 13006 for a few node types. Files say
# how their schema differs from 13006 (an edit sequence per node type), so where the reference is
# ahead of 13006 the edit sequences do not fit; FIXES below holds the 13006 field lists found
# that way, each checked on the data of files.
import re
import sys

FIXES = {
    # 13006 transmits neither list_type, notransmit, finger_index nor finger_block
    # (files insert them), and has a field after `previous` that later schemas dropped
    "LIST": "node_id:d owner:p next:p previous:p unknown:d list_length:d block_length:d size_of_entry:d list_block:p",
    # index_map_offset is later than 13006
    "POINTER_LIS_BLOCK": "n_entries:d next_block:p entries:p[]",
    "REAL_VALUES": "values:f[]",
    "FIELD_NAMES": "names:p[]",
    "TAG_VALUES": "values:d[]",
    "BLEND_BOUND": "node_id:d attributes_groups:p owner:p next:p previous:p geometric_owner:p sense:c boundary:n blend:p",
}
RENAME = {
    ("LINE", 5): "geometric_owner",
    ("ATTRIB_DEF", 3): "actions",
    ("ATTRIB_DEF", 5): "legal_owners",
}


def parse_fields(text):
    out = []
    for item in text.split():
        name, kind = item.split(":")
        count = 1
        if kind.endswith("[]"):
            kind, count = kind[:-2], 0
        elif "[" in kind:
            kind, n = kind[:-1].split("[")
            count = int(n)
        out.append((name, kind, count))
    return out


def main(src, dst):
    txt = open(src, encoding="utf-8", errors="replace").read()
    codes = {}
    table = re.search(r"E\.6 Node Types(.*?)E\.7 Node Classes", txt, re.S).group(1)
    for name, num in re.findall(r"^([A-Z_]+) (\d+) (?:Yes|No)", table, re.M):
        codes[name] = int(num)
    structs = {}
    for m in re.finditer(r"struct ([A-Z_]+)_s[^\n{;]*\n(?:[^\n{]*\n)?\{(.*?)\n\};", txt, re.S):
        name, body = m.group(1), m.group(2)
        fields, pending = [], None
        for line in body.split("\n"):
            line = line.strip()
            cm = re.search(r"//\s*\$([a-z])(\[\s*(\d*)\s*\])?", line)
            decl = line.split("//")[0].strip().rstrip(";").strip()
            if cm:
                count = 1 if not cm.group(2) else (0 if cm.group(3) == "" else int(cm.group(3)))
                if not decl and pending:
                    decl, pending = pending, None
                parts = re.sub(r"\[.*", "", decl).replace("*", " ").split()
                fields.append((parts[-1] if parts else "unnamed", cm.group(1), count))
            elif decl and not decl.startswith(("{", "}")):
                pending = decl
        if fields and name not in structs:
            structs[name] = fields
    lines = [
        "//! Node types of Parasolid XT base schema 13006: code, name and the transmitted fields in",
        "//! order (name, type letter, count; count 0 is the variable-length last field).",
        "//!",
        "//! Generated by `tools/gen_xt_schema.py` from Annex E of Siemens' public JT v10 file format",
        "//! reference; see that script for the node types where the reference is ahead of 13006.",
        "",
        "/// One field of a node: its name, type letter and count (0: variable length).",
        "pub type Field = (&'static str, u8, u16);",
        "",
        "/// The base definition of node type `code`.",
        "pub fn base(code: u16) -> Option<(&'static str, &'static [Field])> {",
        "    NODES.iter().find(|n| n.0 == code).map(|n| (n.1, n.2))",
        "}",
        "",
        "#[rustfmt::skip]",
        "static NODES: &[(u16, &str, &[Field])] = &[",
    ]
    for name, code in sorted(codes.items(), key=lambda kv: kv[1]):
        fields = parse_fields(FIXES[name]) if name in FIXES else structs.get(name)
        if fields is None:
            raise SystemExit("no struct for " + name)
        fields = [(RENAME.get((name, k), f[0]).replace("_ ", "_"), "d" if f[1] == "t" else f[1], f[2]) for k, f in enumerate(fields)]
        body = ", ".join('("%s", b\'%s\', %d)' % f for f in fields)
        lines.append('    (%d, "%s", &[%s]),' % (code, name, body))
    lines += ["];", ""]
    open(dst, "w", encoding="utf-8", newline="\n").write("\n".join(lines))
    print(len(codes), "node types")


main(sys.argv[1], sys.argv[2])
